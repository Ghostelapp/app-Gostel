import base64
import hashlib
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
folder = root / '.cache/mls-wasm'
wasm = (folder / 'ghostel_mls_bg.wasm').read_bytes()
script = (folder / 'ghostel_mls.js').read_text()
script += '\nconst bytes = Uint8Array.from(atob(' + json.dumps(base64.b64encode(wasm).decode()) + '), c => c.charCodeAt(0));\n'
script += '''
const emit = message => {
  if (globalThis.ReactNativeWebView) {
    const json = JSON.stringify(message);
    if (json.length <= 65536 || !Number.isSafeInteger(message.id)) globalThis.ReactNativeWebView.postMessage(json);
    else {
      const total = Math.ceil(json.length / 65536);
      for (let part = 0; part < total; part++) globalThis.ReactNativeWebView.postMessage(JSON.stringify({id: message.id, chunked: true, part, total, chunk: json.slice(part * 65536, (part + 1) * 65536)}));
    }
  }
  else globalThis.postMessage(message);
};
wasm_bindgen.initSync({module: bytes});
globalThis.handleMLS = ({id, input}) => {
  try { emit({id, result: wasm_bindgen.invoke(input)}); }
  catch { emit({id, error: 'MLS runtime failure'}); }
};
const incoming = new Map();
globalThis.receiveMLSChunk = ({id, part, total, chunk}) => {
  if (!Number.isSafeInteger(id) || !Number.isInteger(part) || !Number.isInteger(total) || total < 1 || total > 768 || part < 0 || part >= total || typeof chunk !== 'string' || chunk.length > 65536) return;
  let job = incoming.get(id);
  if (!job) {
    if (incoming.size >= 8) return;
    job = {total, parts: new Map(), timer: setTimeout(() => incoming.delete(id), 30000)}; incoming.set(id, job);
  }
  if (job.total !== total || job.parts.has(part)) return;
  job.parts.set(part, chunk);
  if (job.parts.size === total) {
    clearTimeout(job.timer); incoming.delete(id);
    const input = Array.from({length: total}, (_, index) => job.parts.get(index)).join('');
    globalThis.handleMLS({id, input});
  }
};
if (!globalThis.ReactNativeWebView) globalThis.onmessage = event => globalThis.handleMLS(event.data);
emit({ready: true});
'''
out = root / 'frontend/src/mls/runtime.generated.ts'
source_digest = hashlib.sha256()
for name in ('Cargo.toml', 'Cargo.lock', 'src/lib.rs', 'src/bridge.rs'):
    source_digest.update((root / 'crypto/ghostel-mls' / name).read_bytes())
out.write_text('// Source SHA-256: ' + source_digest.hexdigest() + '\n// Generated by scripts/build-mls-runtime.sh; do not edit.\n// WASM SHA-256: ' + hashlib.sha256(wasm).hexdigest() + '\nexport const MLS_RUNTIME_SCRIPT: string = ' + json.dumps(script) + ';\n')
print('Packaged local MLS runtime:', len(wasm), 'WASM bytes')

notices = (root / 'crypto/ghostel-mls/THIRD_PARTY_NOTICES.md').read_text()
for file in (root / 'frontend/node_modules/expo-sqlite').glob('LICENSE*'):
    if file.is_file(): notices += '\n\n# Expo SQLite 16.0.10\n\n' + file.read_text()
(root / 'frontend/src/mls/licenses.generated.ts').write_text('// Generated third-party notices, including source links for MPL components.\nexport const MLS_LICENSE_NOTICES = ' + json.dumps(notices) + ';\n')
